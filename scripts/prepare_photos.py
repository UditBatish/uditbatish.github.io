#!/usr/bin/env python3
"""Prepare hero photos for the silk backdrop.

Originals live in photos-in/ (gitignored). For each entry below this:
  - applies the phone's EXIF rotation to the pixels
  - crops to the 1.25:1 photo window (fractions of the upright image)
  - stretches levels (2nd/98th percentile) and applies a gamma
  - saves a small greyscale JPEG to public/photos with ALL metadata dropped (no GPS)
  - rewrites src/photos.js in display order, with the side each photo fills

Run: python3 scripts/prepare_photos.py
"""
from pathlib import Path
import numpy as np
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
SRC, OUT = ROOT / 'photos-in', ROOT / 'public' / 'photos'

# name, source, crop (x0, y0, x1, y1), gamma, side, focus x, rotate (degrees CCW).
# Display order. Each photo keeps its own shape (no forced zoom): the hero gives it a
# panel that tall and that wide, flush to its side, and the silk fills the rest.
#   side:  'full' fills the whole field (landscapes, cropped ~2.3:1), blending at both
#          sides. 'left'/'right' fill that half; keep the subject on the outer half,
#          since the inner edge melts into the silk. Never mirror (signs would flip).
#   focus: horizontal point (0..1 of the crop) to keep when phones crop the sides.
# Faces should stay small; the lower ~35% of the panel dissolves into the headline.
PHOTOS = [
    ('bali-sunrise',  'bali_solo.jpg',            (0.00, 0.00, 1.00, 1.00), 0.70, 'right', 0.50, 0),
    ('tetons',        'pd_tetons.jpg',            (0.00, 0.31, 1.00, 0.96), 1.90, 'full',  0.55, 0),
    ('golden-gate',   'pd_golden_gate.jpg',       (0.00, 0.22, 1.00, 0.78), 1.70, 'full',  0.40, 0),
    ('nyc',           'nyc_brooklyn_licensed.jpg', (0.00, 0.27, 1.00, 0.78), 1.90, 'full', 0.62, 0),
    ('peaks',         'pd_yellowstone_peaks.jpg', (0.00, 0.14, 1.00, 0.79), 1.30, 'full',  0.55, 0),
    ('lake-peaks',    'web_lake_peaks.jpg',       (0.00, 0.00, 1.00, 1.00), 1.40, 'full',  0.60, 0),
    ('iit-delhi',     'iit_delhi.jpg',            (0.00, 0.00, 1.00, 1.00), 1.25, 'full',  0.65, 0),
    ('denali',        'pd_denali.jpg',            (0.00, 0.10, 0.76, 0.60), 1.70, 'full',  0.40, 0),
    ('alpine-lake',   'web_alpine_lake.jpg',      (0.00, 0.06, 1.00, 0.84), 1.40, 'full',  0.50, 0),
    ('bali-group',    'bali_sunrise.jpg',         (0.00, 0.25, 1.00, 0.90), 1.50, 'full',  0.50, 0),
]
# Dropped: Mumbai and the NYC night skyline (Udit's call, 2026-11-07), Golden Gate selfie, Hogwarts, Yellowstone storm, Batur dawn (Udit's call), Longs Peak (a ridge, no visible peaks), Hollywood selfie and Lollapalooza close-up (face too zoomed), hazy lake skyline
# (turns to empty peach), Yellowstone canyon aerial (too busy), indoor group,
# college fest, axe throwing, Bali cafe (all dither to mush).

# Stock (public domain, no credit needed): golden-gate is Carol M. Highsmith / Library of
# Congress; peaks (Yellowstone), tetons and denali are US National Park Service.
# Only ever add public-domain or CC0 stock: Udit wants no credits on the page.
# Exception: web_* (lake-peaks, alpine-lake) are images Udit downloaded himself
# (2026-11-07); their licence is unknown. nyc (Brooklyn Bridge, Surfing the Planet): Udit says he
# is licensed to use it; the crop stops above the watermark corner.
WIDTH = 480

OUT.mkdir(parents=True, exist_ok=True)
for old in OUT.glob('*.jpg'):
    old.unlink()

names = []
for name, src, (x0, y0, x1, y1), gamma, side, focus, rot in PHOTOS:
    im = ImageOps.exif_transpose(Image.open(SRC / src)).convert('L')
    if rot:
        im = im.rotate(rot, expand=True)
    W, H = im.size
    im = im.crop((round(x0 * W), round(y0 * H), round(x1 * W), round(y1 * H)))
    w = min(WIDTH * 1.5 if side == 'full' else WIDTH, im.width)   # full-bleed photos need more cells
    im = im.resize((round(w), round(w * im.height / im.width)), Image.LANCZOS)
    a = np.asarray(im, float)
    lo, hi = np.percentile(a, [2, 98])
    a = np.clip((a - lo) / max(hi - lo, 1), 0, 1) ** gamma
    Image.fromarray((a * 255).astype(np.uint8)).save(OUT / f'{name}.jpg', quality=88, optimize=True)
    names.append((name, side, focus, im.width / im.height))
    print(f'{name}: {im.width}x{im.height}, aspect {im.width / im.height:.2f}')

(ROOT / 'src' / 'photos.js').write_text(
    '// Generated by scripts/prepare_photos.py. Edit the list there, not here.\n'
    'export const photos = [\n' + ''.join(f"  {{ src: '/photos/{n}.jpg', side: '{sd}', focus: {fx} }},\n" for n, sd, fx, _ in names) + '];\n'
)
