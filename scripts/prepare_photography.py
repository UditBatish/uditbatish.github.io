#!/usr/bin/env python3
"""Build the /photography/ page's photos.

To add a photo: drop it in photography-in/ as <id>.jpg (HEIC: convert first with
`sips -s format jpeg in.HEIC --out photography-in/<id>.jpg`), add a line to PHOTOS below
(id, place, and an optional turn), then run:  python3 scripts/prepare_photography.py

The month and year come from the photo's own EXIF date. Leave the place empty ('') if
you'd rather not say. The list order is the order of the tidy grid.

Output: public/photography/<id>.jpg (large, for the lightbox), <id>-s.jpg (the print) and
src/photography-data.js.
"""
from datetime import datetime
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'photography-in'
OUT = ROOT / 'public' / 'photography'
DATA = ROOT / 'src' / 'photography-data.js'

PHOTOS = [  # id, place, quarter turns anticlockwise (for the odd sideways shot)
    ('big-sur', 'Big Sur, California', 0),
    ('batur-sunrise', 'Mount Batur, Bali', 0),
    ('jeddah-flowers', 'Jeddah', 0),
    ('over-oregon', 'Over Oregon', 0),
    ('bylakuppe', 'Bylakuppe, Karnataka', 0),
    ('san-francisco', 'San Francisco', 0),
    ('yellowstone', 'Yellowstone', 0),
    ('pug', 'Panchkula', 0),
    ('stanford', 'Stanford', 0),
    ('canggu', 'Canggu, Bali', 0),
    ('jeddah-lights', 'Jeddah', 0),
    ('cubbon-park', 'Cubbon Park, Bengaluru', 0),
    ('riyadh', 'Riyadh', 0),
    ('coorg-path', 'Coorg', 0),
    ('batur-me', 'Mount Batur, Bali', 0),
    ('bengaluru-lake', 'Bengaluru', 1),
    ('berkeley-bibimbap', 'Berkeley', 0),
    ('sunder-nursery', 'Sunder Nursery, Delhi', 0),
    ('lionhill', 'Bengaluru', 0),
    ('dubai', 'Dubai', 0),
    ('bali-temple', 'Bali', 0),
    ('jeddah-rain', 'Jeddah', 0),
    ('gurugram-track', 'Gurugram', 0),
    ('chandigarh-cabin', 'Chandigarh', 0),
    ('bharat-mandapam', 'Bharat Mandapam, Delhi', 0),
    ('coorg-viewpoint', 'Coorg', 0),
    ('lion', 'Panchkula', 0),
    ('gurugram-canopy', 'Gurugram', 0),
    ('chennai', 'Chennai', 0),
    ('batur-crew', 'Mount Batur, Bali', 0),
    ('bengaluru-pool', 'Bengaluru', 0),
    ('night-plane', '', 0),
    ('coorg-garden', 'Coorg', 0),
    ('gurugram-trees', 'Gurugram', 0),
    ('solar-roof', '', 0),
    ('bengaluru-morning', 'Bengaluru', 0),
    ('portrait', '', 0),
]

def taken(im):
    ex = im.getexif()
    raw = ex.get_ifd(0x8769).get(36867) or ex.get(306)
    return datetime.strptime(raw, '%Y:%m:%d %H:%M:%S').strftime('%b %Y') if raw else ''

OUT.mkdir(parents=True, exist_ok=True)
rows = []
for pid, place, turns in PHOTOS:
    im = Image.open(SRC / f'{pid}.jpg')
    when = taken(im)
    im = ImageOps.exif_transpose(im).convert('RGB')
    if turns:
        im = im.rotate(90 * turns, expand=True)
    for suffix, side, q in (('', 1800, 82), ('-s', 640, 80)):
        out = im.copy()
        out.thumbnail((side, side), Image.LANCZOS)
        out.save(OUT / f'{pid}{suffix}.jpg', quality=q, optimize=True, progressive=True)
    rows.append(f"  {{ id: '{pid}', place: {place!r}, when: '{when}', w: {im.width}, h: {im.height} }},")

DATA.write_text('// Generated by scripts/prepare_photography.py. Edit the list there, not here.\n'
                'export const photos = [\n' + '\n'.join(rows) + '\n];\n')
print(f'wrote {len(rows)} photos')
